"""Build the SCTP list for the SME Workforce Pulse from the Course Finder's published data.

Run:  python3 sctp_build.py
Reads  ../../projects/course-finder/data/<sector>.json   (every SkillsFuture course, already sorted
       into a sector by the Course Finder's keyword rules)
       ../course-finder/data/meta.json                   (directory id and last-updated date)
Writes data/sctp.json   (SCTP programmes of the five polytechnics and ITE, one entry per programme)

If the input is missing, or the result looks wrong (under 40 programmes, or an institution with
none), it prints a WARN line and leaves the existing sctp.json alone, so a bad Course Finder month
never blocks the MOM data refresh.
"""
import json, re, pathlib, os, tempfile

HERE = pathlib.Path(__file__).parent
COURSES = HERE.parent.parent / "projects" / "course-finder" / "data"
META = HERE.parent / "course-finder" / "data" / "meta.json"
OUT = HERE / "data" / "sctp.json"

# provider name in the directory -> code; the order is the output order
INSTITUTIONS = {
    "Republic Polytechnic": "RP",
    "Ngee Ann Polytechnic": "NP",
    "Nanyang Polytechnic": "NYP",
    "Singapore Polytechnic": "SP",
    "Temasek Polytechnic": "TP",
    "Institute of Technical Education": "ITE",
}
ORDER = list(INSTITUTIONS.values())
MIN_PROGRAMMES = 40

IS_SCTP = re.compile(r"\bSCTP\b|career transition programme", re.I)
IS_MODULE = re.compile(r"\bmodule\b|part of sctp|accreditation only", re.I)
HAS_TAG = re.compile(r"^\s*[\(\[]\s*SCTP\s*[\)\]]", re.I)
IS_TA = re.compile(r"eligible for .*TA|TA-eligible", re.I)
NOISE = re.compile(r"eligible|\bTA\b|TA-eligible|classroom|synchronous|asynchronous|e-?learning|full[- ]?time|"
                   r"part[- ]?time|blended|online|in-person|face-to-face", re.I)


def clean(t):
    """Strip the SCTP tag and delivery notes from a course title."""
    t = re.sub(r"^\s*[\(\[]?\s*SCTP\s*(module)?\s*[\)\]]?\s*[-:–]?\s*", "", t, flags=re.I)
    t = re.sub(r"^(for|in|on)\s+", "", t, flags=re.I)
    m = re.match(r"^\[([^\]]+)\]\s*(.*)$", t)
    if m:
        t = m.group(1) + " " + m.group(2)
    prev = None
    while prev != t:  # trailing bracket groups, only when they are delivery / TA notes
        prev = t
        m = re.search(r"\s*[\(\[]([^\(\)\[\]]*)[\)\]]\s*$", t)
        if m and NOISE.search(m.group(1)):
            t = t[:m.start()]
    t = re.sub(r"\s*-?\s*(full|part)[- ]time$", "", t, flags=re.I)
    t = re.sub(r"^WSQ\s+", "", t)
    return re.sub(r"\s+", " ", t).strip(" -–:")


def key(t):
    return re.sub(r"[^a-z0-9]+", " ", t.lower().replace("&", "and")).strip()


def collect():
    """Return the programmes found in the Course Finder files, or None if the files are missing."""
    files = sorted(COURSES.glob("*.json"))
    if not files:
        return None
    progs = {}
    for f in files:
        data = json.loads(f.read_text())
        sector = "cross" if f.stem == "general" else f.stem
        providers = data["p"]
        for row in data["c"]:
            ref, title, pid = row[0], row[1], row[2]
            inst = INSTITUTIONS.get(providers.get(str(pid), [None])[0])
            if not inst or not IS_SCTP.search(title) or IS_MODULE.search(title):
                continue
            if not HAS_TAG.match(title) and not IS_TA.search(title):
                continue  # e.g. TP's "SCTP Beyond the GIG" modules
            name = clean(title)
            p = progs.setdefault((inst, key(name)), {"inst": inst, "title": name, "sector": sector, "refs": []})
            p["refs"].append(ref)
    return sorted(progs.values(), key=lambda p: (ORDER.index(p["inst"]), p["title"].lower()))


def main():
    try:
        meta = json.loads(META.read_text())["datasets"]["directory"]
        programmes = collect()
    except (OSError, KeyError, ValueError) as e:
        print(f"WARN sctp_build: input unreadable ({e}); sctp.json left as it was")
        return
    if programmes is None:
        print(f"WARN sctp_build: no Course Finder files in {COURSES}; sctp.json left as it was")
        return
    counts = {c: sum(1 for p in programmes if p["inst"] == c) for c in ORDER}
    if len(programmes) < MIN_PROGRAMMES or not all(counts.values()):
        print(f"WARN sctp_build: result looks wrong ({len(programmes)} programmes, {counts}); sctp.json left as it was")
        return
    old = json.loads(OUT.read_text())
    out = {
        "_note": "Generated by sctp_build.py from the Course Finder's data (SkillsFuture course directory, SWDA, via data.gov.sg). "
                 "Sector is the Course Finder's keyword-rule sector for the course. Do not edit by hand.",
        "collected": meta["updated"][:10],
        "source": {
            "dataset": meta["title"],
            "id": meta["id"],
            "publisher": meta["publisher"],
            "via": "Course Finder data, projects/course-finder/data",
        },
        "institutions": old["institutions"],
        "programmes": programmes,
    }
    fd, tmp = tempfile.mkstemp(dir=OUT.parent, suffix=".tmp")
    with os.fdopen(fd, "w") as fh:
        json.dump(out, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    os.replace(tmp, OUT)
    print(f"sctp.json: {len(programmes)} programmes as of {out['collected']} (" +
          ", ".join(f"{c} {n}" for c, n in counts.items()) + ")")


if __name__ == "__main__":
    main()
