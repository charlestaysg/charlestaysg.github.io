  const HTML_LANG = { en: 'en-SG', zh: 'zh-Hans-SG', ta: 'ta-SG', bn: 'bn', my: 'my', th: 'th' };

  // Keys that carry safety meaning. Every language must have all of them before it is marked reviewed.
  const SAFETY_RE = /^(verdict\.|reason\.|act\.|note\.|sx\.|sched\.|wr\.target\.|wr\.rest\.need\.|brk\.|uv\.|sup\.plan\.|chip\.also\.uv$|wr\.honest$|wr\.tip$|wr\.due$|wr\.wasDue$|btn\.call995$|app\.subline$|chip\.airDelayed$|banner\.demo$|why\.rule\.|brief\.|sup\.check\.)/;
  const SAFETY_KEYS = Object.keys(en).filter(k => SAFETY_RE.test(k) && k !== 'meta');

  function lookup(lang, key) {
    const L = STRINGS[lang];
    if (L && key !== 'meta' && Object.prototype.hasOwnProperty.call(L, key)) return L[key];
    return undefined;
  }
  /** t(key, params, lang): falls back to English, then to the key itself. */
  function t(key, params, lang) {
    let s = lookup(lang || 'en', key);
    if (s === undefined) s = lookup('en', key);
    if (s === undefined) return key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] == null ? m : String(params[k])));
    return s;
  }
  function isReviewed(lang) { return !!(STRINGS[lang] && STRINGS[lang].meta && STRINGS[lang].meta.reviewed); }
  function missingKeys(lang, keys) {
    return (keys || SAFETY_KEYS).filter(k => lookup(lang, k) === undefined);
  }

  const api = { STRINGS, SAFETY_KEYS, LANGS, HTML_LANG, t, isReviewed, missingKeys };
